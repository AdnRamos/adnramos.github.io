let DATA = { projects: { featured: [], exclude: [] }, repos: null };
const nodes = [...document.querySelectorAll('[data-i18n]')];
const PT = Object.fromEntries(nodes.map(n => [n.dataset.i18n, n.textContent]));
Object.assign(PT, { updated: 'atualizado em', private: 'Código privado', research_w: 'Trabalho acadêmico', demo: 'Ver demo →' });
const root = document.documentElement;
const L = () => (root.lang === 'en' ? 'en' : 'pt');

function setLang(l) {
  root.lang = l === 'en' ? 'en' : 'pt-BR';
  nodes.forEach(n => { n.textContent = (l === 'en' ? EN : PT)[n.dataset.i18n]; });
  document.getElementById('lang').textContent = l === 'en' ? 'PT' : 'EN';
  renderProjects();
  renderStats();
  try { localStorage.setItem('lang', l); } catch (e) {}
}
document.getElementById('lang').addEventListener('click', () => setLang(root.lang === 'en' ? 'pt' : 'en'));

document.getElementById('theme').addEventListener('click', () => {
  const t = root.dataset.theme === 'light' ? 'dark' : 'light';
  root.dataset.theme = t;
  document.querySelector('meta[name="theme-color"]').content = t === 'light' ? '#f7f8fb' : '#0b0d12';
  try { localStorage.setItem('theme', t); } catch (e) {}
});

const esc = (t) => String(t ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const safeUrl = (u) => (/^https?:\/\//.test(u || '') ? u : '#');
const fmtDate = (iso) => new Date(iso).toLocaleDateString(L() === 'en' ? 'en-US' : 'pt-BR', { month: 'short', year: 'numeric' });
const tr = (k) => (L() === 'en' ? EN : PT)[k] || '';

function renderProjects() {
  const lang = L();
  const repos = new Map((DATA.repos?.repos || []).map((r) => [r.name, r]));
  const exclude = new Set([...DATA.projects.exclude, ...DATA.projects.featured.map((p) => p.repo).filter(Boolean)]);

  document.getElementById('featured').innerHTML = DATA.projects.featured.map((p) => {
    const r = p.repo && repos.get(p.repo);
    let foot;
    if (p.private) foot = `<span class="priv">${esc(tr('private'))}</span>`;
    else if (p.note) foot = `<span class="priv">${esc(p.note[lang])}</span>`;
    else if (p.link || r) foot = `<a href="${esc(safeUrl(p.link || r.url))}" target="_blank" rel="noopener">GitHub →</a>`;
    else foot = '';
    const meta = r ? `<span class="meta">${r.stars > 0 ? '★ ' + r.stars + ' · ' : ''}${esc(tr('updated'))} ${esc(fmtDate(r.pushed_at))}</span>` : '';
    return `<article class="card${p.big ? ' feature' : ''}">
      <span class="tag-top">${esc(p.tag[lang])}</span>
      <h3>${esc(p.title)}</h3>
      <p>${esc(p.desc[lang])}</p>
      <ul class="tags">${p.stack.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>
      <div class="foot-row">${foot}${meta}</div>
    </article>`;
  }).join('');

  const others = (DATA.repos?.repos || []).filter((r) => !exclude.has(r.name) && r.description).slice(0, 6);
  document.getElementById('others-wrap').hidden = !others.length;
  document.getElementById('others').innerHTML = others.map((r) => `<article class="card">
      <span class="tag-top">${esc(r.language || 'GitHub')}</span>
      <h3>${esc(r.name)}</h3>
      <p>${esc(r.description)}</p>
      <div class="foot-row"><a href="${esc(safeUrl(r.homepage || r.url))}" target="_blank" rel="noopener">${r.homepage ? esc(tr('demo')) : 'GitHub →'}</a><span class="meta">${r.stars > 0 ? '★ ' + r.stars + ' · ' : ''}${esc(tr('updated'))} ${esc(fmtDate(r.pushed_at))}</span></div>
    </article>`).join('');
  observe(document.querySelectorAll('#featured .card, #others .card'));
}

function renderStats() {
  const u = DATA.repos?.user;
  if (!u) return;
  const num = (n) => new Intl.NumberFormat(L() === 'en' ? 'en-US' : 'pt-BR').format(n);
  const set = (id, v) => { if (v != null) document.getElementById(id).textContent = v; };
  set('stat-repos', u.public_repos + '+');
  set('stat-contrib', u.contributions != null ? num(u.contributions) : null);
  set('stat-followers', num(u.followers));
  set('stat-stars', num(u.stars));
  set('stat-since', new Date(u.created_at).getFullYear());
  const langs = u.languages || [];
  document.getElementById('langs').hidden = !langs.length;
  const colors = ['#818cf8', '#22d3ee', '#34d399', '#fbbf24', '#f472b6', '#94a3b8'];
  document.getElementById('langbar').innerHTML = langs.map((l, i) => `<span style="width:${l.percent}%;background:${colors[i]}" title="${esc(l.name)} ${l.percent}%"></span>`).join('');
  document.getElementById('langlist').innerHTML = langs.map((l, i) => `<li><i style="background:${colors[i]}"></i>${esc(l.name)} <b>${l.percent}%</b></li>`).join('');
}

async function load() {
  const j = (f) => fetch(f, { cache: 'no-cache' }).then((r) => (r.ok ? r.json() : Promise.reject(f)));
  const [p, r] = await Promise.allSettled([j('data/projects.json'), j('data/repos.json')]);
  if (p.status === 'fulfilled') DATA.projects = p.value;
  if (r.status === 'fulfilled') DATA.repos = r.value;
  renderProjects();
  renderStats();
}

